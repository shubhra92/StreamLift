import crypto from "crypto";
import { and, count, desc, eq, gt, isNull, lt } from "drizzle-orm";
import { db } from "../db";
import { tvDevices, tvPairings } from "../db/schema";
import type { TvDevice } from "../db/schema";
import {
  TV_APPROVED_TOKEN_WINDOW_MS,
  TV_CODE_ALPHABET,
  TV_CODE_LENGTH,
  TV_CODE_TTL_MS,
  TV_DEVICE_ONLINE_MS,
  TV_MAX_DEVICES_PER_GUEST,
  isValidTvCode,
  normalizeTvCode,
} from "./tvConstants";
import { tvHash, tvRandomToken } from "./tvCrypto";
import type { TvDeviceSummary } from "./tvTypes";

export class TvPairingError extends Error {
  status: number;

  constructor(message: string, status = 400) {
    super(message);
    this.status = status;
  }
}

export interface StartPairingInput {
  deviceSecret: string;
  deviceName?: string | null;
  model?: string | null;
  appVersion?: string | null;
  ipHash?: string | null;
}

export interface StartedPairing {
  code: string;
  expiresAt: Date;
}

/** A device secret is generated by the TV and never leaves it except in a header. */
export function isValidDeviceSecret(value: unknown): value is string {
  return typeof value === "string" && /^[A-Za-z0-9_-]{32,128}$/.test(value);
}

function cleanText(value: unknown, maxLength: number): string | null {
  if (typeof value !== "string") return null;
  const cleaned = value.replace(/[\u0000-\u001f\u007f]/g, " ").trim();
  return cleaned ? cleaned.slice(0, maxLength) : null;
}

function generateCode(): string {
  let code = "";
  for (let i = 0; i < TV_CODE_LENGTH; i += 1) {
    code += TV_CODE_ALPHABET[crypto.randomInt(0, TV_CODE_ALPHABET.length)];
  }
  return code;
}

/**
 * Create (or replace) the pending pairing for a TV. Replacing an existing
 * pending row is intentional: an app restart gets a fresh, valid code instead
 * of reviving a code the user can no longer see.
 */
export async function startPairing(input: StartPairingInput): Promise<StartedPairing> {
  if (!isValidDeviceSecret(input.deviceSecret)) {
    throw new TvPairingError("Invalid device secret", 400);
  }

  const now = new Date();
  const deviceSecretHash = tvHash(input.deviceSecret);

  // Opportunistic cleanup: expired rows cannot be approved or polled.
  await db
    .delete(tvPairings)
    .where(lt(tvPairings.expiresAt, new Date(now.getTime() - 60 * 60 * 1000)));

  await db
    .delete(tvPairings)
    .where(and(eq(tvPairings.deviceSecretHash, deviceSecretHash), eq(tvPairings.status, "pending")));

  if (input.ipHash) {
    const [active] = await db
      .select({ value: count() })
      .from(tvPairings)
      .where(
        and(
          eq(tvPairings.ipHash, input.ipHash),
          eq(tvPairings.status, "pending"),
          gt(tvPairings.expiresAt, now),
        ),
      );
    if (Number(active?.value ?? 0) >= 5) {
      throw new TvPairingError("Too many pairing codes are active. Wait a few minutes and try again.", 429);
    }
  }

  let code = "";
  for (let attempt = 0; attempt < 12; attempt += 1) {
    const candidate = generateCode();
    const [collision] = await db
      .select({ id: tvPairings.id })
      .from(tvPairings)
      .where(
        and(
          eq(tvPairings.codeHash, tvHash(candidate)),
          eq(tvPairings.status, "pending"),
          gt(tvPairings.expiresAt, now),
        ),
      )
      .limit(1);
    if (!collision) {
      code = candidate;
      break;
    }
  }

  if (!code) throw new TvPairingError("Could not allocate a pairing code. Try again.", 503);

  const expiresAt = new Date(now.getTime() + TV_CODE_TTL_MS);
  await db.insert(tvPairings).values({
    codeHash: tvHash(code),
    deviceSecretHash,
    deviceName: cleanText(input.deviceName, 48) ?? "Android TV",
    model: cleanText(input.model, 64),
    appVersion: cleanText(input.appVersion, 32),
    status: "pending",
    ipHash: input.ipHash ?? null,
    expiresAt,
  });

  return { code, expiresAt };
}

export interface PolledPairing {
  status: "pending" | "approved" | "denied" | "expired" | "unknown";
  expiresAt?: Date;
  deviceToken?: string;
  device?: { id: string; name: string };
}

/**
 * Poll a pairing using only the TV-held device secret. The 6-character code is
 * never accepted here, so codes cannot be enumerated by an attacker.
 */
export async function pollPairing(deviceSecret: string): Promise<PolledPairing> {
  if (!isValidDeviceSecret(deviceSecret)) return { status: "unknown" };

  const [pairing] = await db
    .select()
    .from(tvPairings)
    .where(eq(tvPairings.deviceSecretHash, tvHash(deviceSecret)))
    .orderBy(desc(tvPairings.createdAt))
    .limit(1);

  if (!pairing) return { status: "unknown" };

  const now = Date.now();

  if (pairing.status === "pending") {
    if (pairing.expiresAt.getTime() <= now) {
      await db.update(tvPairings).set({ status: "expired" }).where(eq(tvPairings.id, pairing.id));
      return { status: "expired", expiresAt: pairing.expiresAt };
    }
    return { status: "pending", expiresAt: pairing.expiresAt };
  }

  if (pairing.status !== "approved" || !pairing.deviceId) {
    return { status: pairing.status === "denied" ? "denied" : "expired", expiresAt: pairing.expiresAt };
  }

  if (!pairing.approvedAt || now - pairing.approvedAt.getTime() > TV_APPROVED_TOKEN_WINDOW_MS) {
    return { status: "expired", expiresAt: pairing.expiresAt };
  }

  const [device] = await db
    .select()
    .from(tvDevices)
    .where(and(eq(tvDevices.id, pairing.deviceId), isNull(tvDevices.revokedAt)))
    .limit(1);

  if (!device) return { status: "denied" };

  // Issue a fresh token on each approved poll. That makes a lost response safe:
  // the TV simply polls again and stores the newest token.
  const deviceToken = tvRandomToken();
  const seenAt = new Date();
  await db
    .update(tvDevices)
    .set({ tokenHash: tvHash(deviceToken), lastSeenAt: seenAt })
    .where(eq(tvDevices.id, device.id));
  await db
    .update(tvPairings)
    .set({ consumedAt: seenAt })
    .where(eq(tvPairings.id, pairing.id));

  return {
    status: "approved",
    expiresAt: pairing.expiresAt,
    deviceToken,
    device: { id: device.id, name: device.name },
  };
}

export interface ApprovedPairing {
  device: TvDevice;
}

/**
 * Approve a code from the web session. The conditional update makes approval
 * one-shot even if two browsers submit the same code at the same time.
 */
export async function approvePairing(
  rawCode: string,
  guestId: string,
): Promise<ApprovedPairing | { error: string; status: number }> {
  const code = normalizeTvCode(rawCode);
  if (!isValidTvCode(code)) {
    return { error: "Enter the 6-character code shown on your TV.", status: 400 };
  }

  try {
    return await db.transaction(async (tx) => {
      const now = new Date();
      const [pairing] = await tx
        .select()
        .from(tvPairings)
        .where(
          and(
            eq(tvPairings.codeHash, tvHash(code)),
            eq(tvPairings.status, "pending"),
            gt(tvPairings.expiresAt, now),
          ),
        )
        .limit(1);

      if (!pairing) {
        return { error: "That code is invalid or has expired.", status: 404 };
      }

      const [deviceCount] = await tx
        .select({ value: count() })
        .from(tvDevices)
        .where(and(eq(tvDevices.guestId, guestId), isNull(tvDevices.revokedAt)));

      if (Number(deviceCount?.value ?? 0) >= TV_MAX_DEVICES_PER_GUEST) {
        return {
          error: `You already have ${TV_MAX_DEVICES_PER_GUEST} TVs connected. Disconnect one first.`,
          status: 409,
        };
      }

      const [claimed] = await tx
        .update(tvPairings)
        .set({ status: "approved", guestId, approvedAt: now })
        .where(
          and(
            eq(tvPairings.id, pairing.id),
            eq(tvPairings.status, "pending"),
            gt(tvPairings.expiresAt, now),
          ),
        )
        .returning({ id: tvPairings.id });

      if (!claimed) {
        return { error: "That code has already been used.", status: 409 };
      }

      const [device] = await tx
        .insert(tvDevices)
        .values({
          guestId,
          name: pairing.deviceName?.trim() || "Android TV",
          model: pairing.model,
          appVersion: pairing.appVersion,
          lastSeenAt: null,
        })
        .returning();

      await tx.update(tvPairings).set({ deviceId: device.id }).where(eq(tvPairings.id, pairing.id));

      return { device };
    });
  } catch (error) {
    console.error("TV pairing approval failed:", error);
    return { error: "Could not connect this TV. Try again.", status: 500 };
  }
}

export function isTvDeviceOnline(lastSeenAt: Date | null | undefined): boolean {
  return Boolean(lastSeenAt && Date.now() - lastSeenAt.getTime() < TV_DEVICE_ONLINE_MS);
}

export function toDeviceSummary(device: TvDevice): TvDeviceSummary {
  return {
    id: device.id,
    name: device.name,
    model: device.model,
    appVersion: device.appVersion,
    online: Boolean(device.tokenHash) && isTvDeviceOnline(device.lastSeenAt),
    lastSeenAt: device.lastSeenAt?.toISOString() ?? null,
    createdAt: device.createdAt?.toISOString() ?? null,
  };
}

export async function listTvDevices(guestId: string): Promise<TvDeviceSummary[]> {
  const rows = await db
    .select()
    .from(tvDevices)
    .where(and(eq(tvDevices.guestId, guestId), isNull(tvDevices.revokedAt)))
    .orderBy(desc(tvDevices.createdAt));

  return rows.map(toDeviceSummary);
}

export async function revokeTvDevice(guestId: string, deviceId: string): Promise<boolean> {
  const revoked = await db
    .update(tvDevices)
    .set({ revokedAt: new Date(), tokenHash: null })
    .where(
      and(
        eq(tvDevices.id, deviceId),
        eq(tvDevices.guestId, guestId),
        isNull(tvDevices.revokedAt),
      ),
    )
    .returning({ id: tvDevices.id });

  if (revoked.length === 0) return false;

  await db.delete(tvPairings).where(eq(tvPairings.deviceId, deviceId));
  return true;
}

/** Called once the TV has used its token; no further token issuance is needed. */
export async function consumeApprovedPairings(deviceId: string): Promise<void> {
  await db
    .delete(tvPairings)
    .where(and(eq(tvPairings.deviceId, deviceId), eq(tvPairings.status, "approved")));
}
